#!/usr/bin/env python3
"""Assemble Folio's plain CSS and file://-usable catalog; standard library only."""
import argparse
import html
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = ["families/folio/tokens.css", "families/core/base.css",
         "families/core/layouts.css", "families/core/atoms.css"]


def outputs():
    css = "/* Folio CSS — generated by python3 dev/build-folio-css.py.\n"
    css += "   Edit the source modules listed below; projects freeze a copy of this file. */\n"
    for name in PARTS:
        source = (ROOT / name).read_text(encoding="utf-8")
        if "@import" in source or "@font-face" in source:
            raise ValueError(f"{name}: distribution must be standalone; fonts belong to project.json")
        css += f"\n/* ── {name} ── */\n{source.rstrip()}\n"
    catalog = json.loads((ROOT / "dev/folio-css/catalog.json").read_text(encoding="utf-8"))
    catalog["version"] = json.loads((ROOT / "families/folio/family.json").read_text())["version"]
    catalog["components"] += json.loads((ROOT / "dev/folio-css/business-recipes.json").read_text())["components"]
    module_spec = importlib.util.spec_from_file_location("folio_charts", ROOT / "hb/core/charts.py")
    charts = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(charts)
    for example in json.loads((ROOT / "dev/folio-css/chart-examples.json").read_text())["examples"]:
        svg = charts.render_figure(example["spec"])
        catalog["components"].append({
            "id": example["id"], "title": example["title"], "category": "charts",
            "description": example["description"],
            "grammar": "Python 标准库计算几何 → SVG 图形与可编辑 HTML 标签；Folio 颜色与字体变量控制视觉。",
            "classes": ["fl-caption", "fl-mt-2"],
            "limits": "默认 640px 宽；缩小时重新生成并检查最终字号。数据、单位、时期、来源必须齐全。示例值不能当作真实业绩。",
            "data": example["spec"],
            "html": '<figure>' + svg + '<figcaption class="fl-caption fl-mt-2">' + html.escape(example["caption"]) + '</figcaption></figure>',
        })
    ids = []
    for section in ("layouts", "components"):
        for entry in catalog[section]:
            for key in ("id", "title", "category", "description", "grammar", "classes", "limits", "html"):
                if key not in entry:
                    raise ValueError(f"{section}: missing {key}")
            ids.append(entry["id"])
    if len(ids) != len(set(ids)):
        raise ValueError("Catalog IDs must be unique across layouts and components")
    js = "// Generated from catalog.json. Plain script also works when opened as a local file.\n"
    js += "window.FOLIO_CATALOG = " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n"
    return {"families/folio/design.css": css, "dev/folio-css/catalog.js": js}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in outputs have drifted")
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"Built {name}")
    if stale:
        parser.exit(1, "Rebuild with python3 dev/build-folio-css.py: " + ", ".join(stale) + "\n")
    if args.check:
        print("PASS: Folio CSS and catalog match source modules")


if __name__ == "__main__":
    main()
