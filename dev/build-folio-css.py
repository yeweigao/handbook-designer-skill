#!/usr/bin/env python3
"""Assemble Folio's plain CSS and file://-usable catalog; standard library only."""
import argparse
import html
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = ["families/folio/tokens.css", "families/core/base.css",
         "families/core/layouts.css", "families/core/components.css",
         "families/core/variations.css", "families/core/atoms.css"]
GROUPS = (("atoms", "原子"), ("layouts", "布局"),
          ("components", "组件"), ("expressions", "表现与变奏"))


def production_recipes(catalog):
    """Publish the same recipes without the developer website's locations."""
    recipes = {"version": catalog["version"], "coverage": catalog["coverage"],
               "usage": "按 id 选择配方并替换真实内容。assets/images/ 下的图片是项目内示例路径，"
                        "不是随包素材；使用本项目已登记来源的图片。展示尺寸与数据是示意，"
                        "需按实际纸张、内容和最终 PDF 检查。"}
    for section, _ in GROUPS:
        recipes[section] = []
        for original in catalog[section]:
            entry = {key: value for key, value in original.items() if key != "specimenPage"}
            entry["html"] = re.sub(r"(?:\.\./)+samples/native/[^/]+/assets/images/",
                                   "assets/images/", entry["html"])
            encoded = json.dumps(entry, ensure_ascii=False)
            if "dev/" in encoded or "../samples/" in encoded:
                raise ValueError(f"{entry['id']}: production recipe leaks a developer path")
            recipes[section].append(entry)
    return recipes


def recipe_index(recipes):
    """Small, readable entry point; full HTML stays in the adjacent JSON."""
    lines = ["# Folio 配方索引", "",
             "由同一设计系统目录生成；正式用法只需本目录的 `folio.css`、本索引和 [recipes.json](recipes.json)。",
             f"当前 {recipes['coverage']['entries']} 项配方，覆盖 {recipes['coverage']['classes']} 个公开类。"
             "先查阅读任务与类名，再按 id 读取需要的配方；不必整份载入。", "",
             "图片 `assets/images/<文件名>` 是待替换的项目内示例路径，随包不提供图片。"
             "以项目真实内容、已登记图片和画布替换示意；配方展示尺寸、文字和数值不是交付内容。", "",
             "按 id 读取完整 HTML、约束与图表数据：", "", "```bash",
             "python3 - <skill目录>/families/folio/recipes.json photo-pair <<'PY'",
             "import json, sys", "data = json.load(open(sys.argv[1], encoding='utf-8'))",
             "entry = next((item for group in ('atoms', 'layouts', 'components', 'expressions')",
             "              for item in data[group] if item['id'] == sys.argv[2]), None)",
             "if entry is None: raise SystemExit('未找到配方 ID：' + sys.argv[2])",
             "print(json.dumps(entry, ensure_ascii=False, indent=2))", "PY", "```", ""]
    for section, title in GROUPS:
        lines.extend([f"## {title} · {len(recipes[section])} 项", "",
                      "| ID | 名称 | 公开类 |", "|---|---|---|"])
        for entry in recipes[section]:
            title = entry["title"].replace("|", "\\|")
            classes = " · ".join(f"`{name}`" for name in entry["classes"])
            lines.append(f"| `{entry['id']}` | {title} | {classes} |")
        lines.append("")
    return "\n".join(lines)


def outputs():
    css = "/* Folio CSS — generated by python3 dev/build-folio-css.py.\n"
    css += "   Edit the source modules listed below; projects freeze a copy of this file. */\n"
    for name in PARTS:
        source = (ROOT / name).read_text(encoding="utf-8")
        if "@import" in source or "@font-face" in source:
            raise ValueError(f"{name}: distribution must be standalone; fonts belong to project.json")
        css += f"\n/* ── {name} ── */\n{source.rstrip()}\n"
    catalog = json.loads((ROOT / "dev/folio-css/catalog.json").read_text(encoding="utf-8"))
    catalog["version"] = json.loads((ROOT / "families/folio/family.json").read_text())["version"]
    catalog["components"] += json.loads((ROOT / "dev/folio-css/business-recipes.json").read_text())["components"]
    catalog["components"] += json.loads((ROOT / "dev/folio-css/swiss-recipes.json").read_text())["components"]
    system = json.loads((ROOT / "dev/folio-css/system-recipes.json").read_text())
    # `variations.css` is the layer name; the catalog groups those recipes under
    # `expressions`. Accept either key so a recipe filed under the CSS layer name
    # is never dropped silently.
    for section in ("atoms", "layouts", "components", "expressions", "variations"):
        target = "expressions" if section == "variations" else section
        catalog.setdefault(target, []).extend(system.get(section, []))
    module_spec = importlib.util.spec_from_file_location("folio_charts", ROOT / "hb/core/charts.py")
    charts = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(charts)
    for example in json.loads((ROOT / "dev/folio-css/chart-examples.json").read_text())["examples"]:
        svg = charts.render_figure(example["spec"])
        catalog["components"].append({
            "id": example["id"], "title": example["title"], "category": "charts",
            "description": example["description"],
            "grammar": "Python 标准库计算几何 → SVG 图形与可编辑 HTML 标签；Folio 颜色与字体变量控制视觉。",
            "classes": ["fl-caption", "fl-mt-2"],
            "limits": "默认 640px 宽；缩小时重新生成并检查最终字号。数据、单位、时期、来源必须齐全。示例值不能当作真实业绩。",
            "data": example["spec"],
            "html": '<figure>' + svg + '<figcaption class="fl-caption fl-mt-2">' + html.escape(example["caption"]) + '</figcaption></figure>',
        })
    ids = []
    for section in ("atoms", "layouts", "components", "expressions"):
        for entry in catalog[section]:
            for key in ("id", "title", "category", "description", "grammar", "classes", "limits", "html"):
                if key not in entry:
                    raise ValueError(f"{section}: missing {key}")
            ids.append(entry["id"])
            entry["specimenPage"] = {"id": entry["id"], "label": entry["title"]}
    if len(ids) != len(set(ids)):
        raise ValueError("Catalog IDs must be unique across layouts and components")
    # Public class inventory prevents new CSS capabilities disappearing from the showcase.
    selectors = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    public = set(re.findall(r"\.(fl-[A-Za-z0-9_-]+)", selectors))
    class_map = {name: [] for name in sorted(public)}
    for section in ("atoms", "layouts", "components", "expressions"):
        for entry in catalog[section]:
            named = set(entry["classes"])
            unknown = named - public
            if unknown:
                raise ValueError(f"{entry['id']}: unknown public classes {sorted(unknown)}")
            for name in named:
                class_map[name].append(entry["id"])
    missing = [name for name, entries in class_map.items() if not entries]
    if missing:
        raise ValueError("Public CSS missing catalog coverage: " + ", ".join(missing))
    inventory = {"version": catalog["version"], "class_count": len(class_map),
                 "entry_count": len(ids), "classes": class_map,
                 "scope": "All public fl-* classes indexed by API group; representative compositions, not every permutation."}
    catalog["coverage"] = {"classes": len(class_map), "entries": len(ids)}
    recipes = production_recipes(catalog)
    js = "// Generated from catalog.json. Plain script also works when opened as a local file.\n"
    js += "window.FOLIO_CATALOG = " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n"
    return {"families/folio/folio.css": css,
            "families/folio/recipes.json": json.dumps(recipes, ensure_ascii=False, indent=2) + "\n",
            "families/folio/recipe-index.md": recipe_index(recipes),
            "dev/folio-css/catalog.js": js,
            "dev/folio-css/api-coverage.json": json.dumps(inventory, ensure_ascii=False, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in outputs have drifted")
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"Built {name}")
    if stale:
        parser.exit(1, "Rebuild with python3 dev/build-folio-css.py: " + ", ".join(stale) + "\n")
    if args.check:
        print("PASS: Folio CSS and catalog match source modules")


if __name__ == "__main__":
    main()
